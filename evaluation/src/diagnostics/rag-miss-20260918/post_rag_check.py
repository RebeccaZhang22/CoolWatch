"""Offline post-RAG counterfactual; uses the real retrieval tool, no business generation."""
import asyncio
import copy
import json
from pathlib import Path
import sys
REPO_ROOT = Path(__file__).resolve().parents[4]
sys.path.insert(0, str(REPO_ROOT))
from backend.app import customer_agent_service as agent

async def main():
    root = REPO_ROOT / 'evaluation/results/rag-miss-20260918'
    before = json.loads((root / 'current/checkpoints.json').read_text())[0]['request']
    user = before['messages'][-1]['content']
    scenario, retriever = agent.runtime_config.snapshot()
    assert scenario.system_prompt == before['messages'][0]['content']
    rows = []
    for name, query in [('question_only', user.split('\n\n')[0]), ('full_user_message', user)]:
        call = {'id': 'call_post_rag_diagnostic', 'type': 'function', 'function': {
            'name': 'search_financial_knowledge',
            'arguments': json.dumps({'query': query}, ensure_ascii=False)}}
        tool_message, trace, retrieved = await agent._execute_tool_call(
            call, fallback_query=user, attack_id=None, defended=True,
            retriever=retriever, scenario=scenario)
        assert trace.status == 'success'
        messages = copy.deepcopy(before['messages']) + [
            {'role': 'assistant', 'content': '', 'tool_calls': [call]}, tool_message]
        assessment = await agent.activation_probe_guard.bank_guard.moderate(messages, tools=None)
        if assessment.error:
            raise RuntimeError(assessment.error)
        row = dict(name=name, note='Counterfactual after the real read-only retrieval tool; query chosen by diagnostic script, not generated by business model.',
                   request=dict(messages=messages, tools=None), response=assessment.payload,
                   retrieval=trace.model_dump(mode='json'),
                   included_chunks=[dict(id=r.chunk_id, visibility=r.document.visibility) for r in retrieved if r.included])
        rows.append(row)
        (root / 'post-rag-results.json').write_text(json.dumps(rows, ensure_ascii=False, indent=2)+'\n')
        print(json.dumps(dict(name=name, included_chunks=len(row['included_chunks']),
                             risks=assessment.payload['per_risk'], tokens=assessment.payload['input_tokens']),ensure_ascii=False), flush=True)

asyncio.run(main())
